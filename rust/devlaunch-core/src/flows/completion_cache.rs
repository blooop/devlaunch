//! The completion cache: what the shell offers, and how stale it is allowed to be.
//!
//! Two files in devlaunch's cache directory, written together and read by
//! different things:
//!
//! - `completions.json` — the machine-readable copy. `dl --completion-data` hands
//!   it back verbatim and `dl --repos` reads its `repos` list. It also carries the
//!   clock: the file's own mtime is the freshness timestamp.
//! - `completions.bash` — four shell assignments the shipped completion script
//!   sources. That script spells the path as
//!   `${XDG_CACHE_HOME:-$HOME/.cache}/devlaunch/completions.bash` and nothing
//!   negotiates it at runtime, which is what `flows::completion`'s
//!   `the_payload_reads_the_cache_the_listing_side_writes` pins from the other
//!   side.
//!
//! Ported from `dl.py`'s `_get_cache_dir`, `read_completion_cache`,
//! `write_completion_cache`, `write_bash_completion_cache`,
//! `get_remote_branches`, `get_local_branches`, `update_completion_cache`,
//! `completion_cache_age_seconds`, `completion_cache_is_fresh` and
//! `wants_startup_cache_refresh`; see docs/rust-rewrite-plan.md (M5).
//!
//! # Why an hour
//!
//! Refreshing means a `git ls-remote` per known repo, so doing it on every
//! invocation costs seconds of machine for a list of names that barely moves. An
//! hour mirrors the worktree config's `fetch_interval`, which already decides how
//! stale devlaunch is willing to let its view of a repo's branches get — and
//! branch names are exactly what the expensive part of this refresh collects, so
//! the two should agree. `dl --refresh` remains the escape hatch when a user wants
//! it now.
//!
//! The timestamp is the file's mtime rather than a field inside it: the write
//! renames the finished file into place, so mtime marks a *completed* refresh;
//! caches written by earlier versions carry no timestamp field and would otherwise
//! read as infinitely stale; and a `stat` keeps the check free on the path whose
//! entire purpose is to do no work.
//!
//! # What is deliberately not here
//!
//! - **The background self-spawn.** Python's `update_cache_background` forks
//!   `python -m devlaunch.dl --update-cache` and forgets it. Which program to
//!   re-exec is the binary's own name, so it lands with the binary (M6).
//! - **The repo-fetch sweep.** `sweep_repo_fetches` shares the detached child with
//!   this refresh but does something else entirely — it fetches the bare clones
//!   under the repo locks — and belongs with the storage flows (M6).

