/// How long a completion cache is considered current.
pub(crate) const COMPLETION_CACHE_TTL: Duration = Duration::from_secs(3600);

/// The JSON cache's file name, under devlaunch's cache directory.
const CACHE_FILE: &str = "completions.json";

/// The shell-sourceable cache's file name. The shipped completion script has this
/// path built in.
const BASH_CACHE_FILE: &str = "completions.bash";

/// The first line of `completions.bash`, so a person who opens it knows not to.
const BASH_HEADER: &str = "# Auto-generated by dl - do not edit";

/// The JSON cache inside *cache_dir*.
pub fn cache_path(cache_dir: &Path) -> PathBuf {
    cache_dir.join(CACHE_FILE)
}

/// The shell cache inside *cache_dir*.
pub(crate) fn bash_cache_path(cache_dir: &Path) -> PathBuf {
    cache_dir.join(BASH_CACHE_FILE)
}

/// What the shell may complete: four lists, in the order the cache carries them.
///
/// The field names are the JSON keys, and the order is the key order — the cutover
/// checklist requires both binaries to write this file identically, so this
/// declaration is the wire format.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct CompletionData {
    /// Every devpod workspace id.
    #[serde(default)]
    pub workspaces: Vec<String>,
    /// Every known `owner/repo`, sorted.
    #[serde(default)]
    pub repos: Vec<String>,
    /// Every known owner, sorted.
    #[serde(default)]
    pub owners: Vec<String>,
    /// Every known `owner/repo@branch`, sorted within each repo.
    #[serde(default)]
    pub branches: Vec<String>,
}

impl CompletionData {
    /// The document as `dl --completion-data` prints it: one line, Python's
    /// spacing.
    pub fn as_json_line(&self) -> String {
        json_as_python_writes_it(
            &serde_json::to_value(self).unwrap_or_else(|_| serde_json::json!({})),
        )
    }

    /// The shell file's four assignments, with the do-not-edit header.
    ///
    /// Space-joined inside double quotes, which is what `compgen -W` wants — and
    /// which is why a branch name with a space in it could not be completed
    /// either before or after the port.
    pub(crate) fn as_bash(&self) -> String {
        let mut text = String::from(BASH_HEADER);
        for (name, values) in [
            ("DL_WORKSPACES", &self.workspaces),
            ("DL_REPOS", &self.repos),
            ("DL_OWNERS", &self.owners),
            ("DL_BRANCHES", &self.branches),
        ] {
            text.push_str(&format!("\n{name}=\"{}\"", values.join(" ")));
        }
        text.push('\n');
        text
    }
}

/// Read the cache, or nothing when there is none to read.
///
/// A file that is not there, cannot be opened, or is not the document this build
/// writes all answer the same thing: there is no cache. That is what Python
/// answers too — its readers then either fall back to asking devpod
/// (`--completion-data`, `--repos`) or refresh.
pub fn read_completion_cache(path: &Path) -> Option<CompletionData> {
    let text = std::fs::read_to_string(path).ok()?;
    serde_json::from_str(&text).ok()
}

/// Write the JSON cache, atomically.
///
/// Written to a temp file in the same directory and renamed over the real path, so
/// an interrupted write cannot leave a half-cache behind and mtime marks a
/// *completed* refresh.
pub(crate) fn write_completion_cache(path: &Path, data: &CompletionData) -> io::Result<()> {
    write_atomically(path, &data.as_json_line())
}

/// Write the shell cache, atomically.
pub(crate) fn write_bash_completion_cache(path: &Path, data: &CompletionData) -> io::Result<()> {
    write_atomically(path, &data.as_bash())
}

/// *text* into *path*, via a temp file in the same directory.
///
/// **The temp file's name is Python's, and Python's is a hazard.** Python builds it
/// with `Path.with_suffix(".tmp")`, which *replaces* the extension — so
/// `completions.json` and `completions.bash` both stage through
/// `completions.tmp`. Two refreshes running at once can therefore have one's bash
/// text renamed over the other's JSON cache. It is reproduced rather than fixed
/// because a fix is a behavioural divergence and those are numbered in
/// docs/rust-rewrite-plan.md; this comment is the note asking for a row. Nothing
/// is corrupted beyond one cache file, and the next refresh rewrites it.
fn write_atomically(path: &Path, text: &str) -> io::Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let staged = path.with_extension("tmp");
    std::fs::write(&staged, text)?;
    std::fs::rename(&staged, path)
}

/// How long ago the cache was written, or nothing when there is no cache.
///
/// Never negative: a cache stamped in the future is zero seconds old, as Python's
/// `max(0.0, …)` makes it, rather than an error a caller would have to have an
/// answer for.
pub(crate) fn completion_cache_age(path: &Path, now: SystemTime) -> Option<Duration> {
    let modified = std::fs::metadata(path)
        .and_then(|meta| meta.modified())
        .ok()?;
    Some(now.duration_since(modified).unwrap_or(Duration::ZERO))
}

/// Whether the cache is new enough to leave alone.
pub fn completion_cache_is_fresh(path: &Path) -> bool {
    is_fresh_at(path, SystemTime::now())
}

fn is_fresh_at(path: &Path, now: SystemTime) -> bool {
    completion_cache_age(path, now).is_some_and(|age| age < COMPLETION_CACHE_TTL)
}

/// The commands that read the completion cache without changing what it describes.
const CACHE_READING_COMMANDS: [&str; 3] = ["--ls", "--repos", "--completion-data"];

/// Whether this invocation should warm the completion cache before running.
///
/// Only the commands that read the cache and leave the workspace list alone.
/// Everything else either has no use for completions (`--help`, `--version`), owns
/// the refresh itself (`--install`, `--refresh`, `--update-cache`), is about to
/// delete the cache directory (`--purge`), or is a workspace command — and those
/// refresh once they are finished, when the workspace list they cache is final,
/// instead of indexing the state they are about to replace.
///
/// No arguments at all is the fuzzy picker, which is a view of the workspace list.
///
/// A pure predicate over argv, and deliberately over *argv* rather than over parsed
/// arguments: the decision has to be made before the command runs, and `dl --help`
/// must not pay for a refresh it has no use for.
pub fn wants_startup_cache_refresh<S: AsRef<str>>(args: &[S]) -> bool {
    match args.first() {
        None => true,
        Some(first) => CACHE_READING_COMMANDS.contains(&first.as_ref()),
    }
}

/// One cache file that could not be written, and what the OS said.
///
/// Python swallows these (`except OSError: pass`) and it is right to: a cache that
/// could not be written is not a reason to fail the command that was warming it.
/// They are carried out rather than dropped so a caller *may* say so.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CacheNotWritten {
    pub path: PathBuf,
    pub reason: String,
}

/// What a refresh collected, and what it could not.
pub struct Refreshed {
    pub data: CompletionData,
    /// Why the workspace names are missing, when they are.
    ///
    /// The one reader of the workspace list that has something to do with a
    /// listing it cannot read. Everywhere else an unreadable listing means the
    /// question cannot be answered at all; here the workspace names are one of
    /// four things being collected and the other three come off the local disk, so
    /// this builds completions out of what it can still see. Refusing would mean an
    /// unreachable devpod stops `dl --install` from installing completions at all,
    /// when what it costs is the workspace names.
    ///
    /// Carried rather than swallowed because `dl --refresh` prints the workspace
    /// count it got, and zero-because-we-could-not-ask must not read as
    /// zero-because-there-are-none.
    pub listing_refused: Option<ListingUnreadable>,
    /// Workspaces whose source devlaunch could not read, so a caller can say which.
    pub unreadable_sources: Vec<UnreadableSource>,
    pub not_written: Vec<CacheNotWritten>,
}

/// Rebuild the completion cache and write both files.
///
/// The workspace names come from devpod; the repos, owners and branches come off
/// the local disk and a `git ls-remote` per repo. Everything is sorted, so two
/// refreshes that saw the same world write the same bytes.
pub fn update_completion_cache(
    context: &mut CommandContext<'_>,
    cache_dir: &Path,
    repos_dir: &Path,
) -> Refreshed {
    let (workspaces, listing_refused) = match context.workspaces() {
        Ok(workspaces) => (workspaces, None),
        Err(refused) => (Vec::new(), Some(refused)),
    };
    let git = context.git();
    let mut discovered = listing::discover_repos_from_workspaces(&git, &workspaces);
    // Merged so that repos cloned locally — even without a devpod workspace yet —
    // appear in completions.
    listing::merge_repos(
        &mut discovered.repos,
        &listing::discover_repos_from_cache_dir(repos_dir),
    );

    let repos = listing::flatten_repos(&discovered.repos);
    let owners = listing::owners_of(&discovered.repos);
    let mut branches = Vec::new();
    for owner_repo in &repos {
        for branch in branches_of(&git, repos_dir, owner_repo) {
            branches.push(format!("{owner_repo}@{branch}"));
        }
    }

    let data = CompletionData {
        workspaces: workspaces
            .into_iter()
            .map(|workspace| workspace.id)
            .collect(),
        repos,
        owners,
        branches,
    };
    let mut not_written = Vec::new();
    for (path, written) in [
        (
            cache_path(cache_dir),
            write_completion_cache(&cache_path(cache_dir), &data),
        ),
        (
            bash_cache_path(cache_dir),
            write_bash_completion_cache(&bash_cache_path(cache_dir), &data),
        ),
    ] {
        if let Err(reason) = written {
            not_written.push(CacheNotWritten {
                path,
                reason: reason.to_string(),
            });
        }
    }
    Refreshed {
        data,
        listing_refused,
        unreadable_sources: discovered.unreadable,
        not_written,
    }
}

/// Every branch of one `owner/repo` worth completing, deduplicated and sorted.
///
/// Remote and local are merged so a branch created by `dl owner/repo@new-branch`
/// completes before it has been pushed anywhere.
fn branches_of(git: &Git<'_>, repos_dir: &Path, owner_repo: &str) -> BTreeSet<String> {
    let mut branches: BTreeSet<String> = remote_branches(git, owner_repo).into_iter().collect();
    branches.extend(local_branches(git, repos_dir, owner_repo));
    branches
}

/// The branches a GitHub repo has, asked over ssh with a five-second ceiling.
///
/// A refusal — no network, no key, a repo that is not there — is an empty list
/// rather than an error: it costs those branch names their completion and nothing
/// else.
pub(crate) fn remote_branches(git: &Git<'_>, owner_repo: &str) -> Vec<String> {
    git.ls_remote_heads_of(&format!("git@github.com:{owner_repo}.git"))
        .said()
        .unwrap_or_default()
}

/// The branches the bare clone in the cache holds.
///
/// No bare clone means no branches and no spawn: this runs once per known repo on
/// a path whose whole point is to be cheap.
pub(crate) fn local_branches(git: &Git<'_>, repos_dir: &Path, owner_repo: &str) -> Vec<String> {
    let Some((owner, repo)) = owner_repo.split_once('/') else {
        return Vec::new();
    };
    let bare = repos_dir.join(owner).join(repo).join(".bare");
    if !bare.is_dir() {
        return Vec::new();
    }
    git.local_branches(&bare).said().unwrap_or_default()
}

