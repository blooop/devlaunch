    #[test]
    fn completions_are_built_from_whatever_can_be_read() {
        // The one reader of the workspace list that has something to do with a
        // listing it cannot read: the workspace names are one of four things being
        // collected, and the other three come off the local disk. Refusing would
        // mean an unreachable devpod stops `dl --install` from installing
        // completions at all.
        let scene = Refresher::new();
        scene.with_bare("blooop", "devlaunch");
        scene.fake.script(
            ["devpod", "list"],
            Response::failed(1, "context not found\n"),
        );
        scene
            .fake
            .script(["git", "ls-remote"], Response::stdout(""));

        let refreshed = scene.refresh();

        assert_eq!(refreshed.data.repos, ["blooop/devlaunch"]);
        assert!(refreshed.data.workspaces.is_empty());
        // Not swallowed: `dl --refresh` prints the workspace count it got, and
        // zero-because-we-could-not-ask must not read as zero-because-there-are-none.
        match refreshed.listing_refused {
            Some(ListingUnreadable::Failed { stderr, .. }) => {
                assert!(stderr.contains("context not found"), "{stderr}");
            }
            other => panic!("expected the refusal to travel, got {other:?}"),
        }
        // And the caches are still written, so completion still offers the repos.
        assert!(cache_path(&scene.cache()).is_file());
        assert!(bash_cache_path(&scene.cache()).is_file());
    }

