    fn git_cli(cwd: &Path, args: &[&str]) -> String {
        let output = Command::new("git")
            .args(args)
            .current_dir(cwd)
            .output()
            .expect("git is installed");
        assert!(
            output.status.success(),
            "git {args:?} in {}: {}",
            cwd.display(),
            String::from_utf8_lossy(&output.stderr)
        );
        String::from_utf8_lossy(&output.stdout).trim().to_owned()
    }

    fn commit(work: &Path, message: &str) {
        git_cli(work, &["add", "-A"]);
        git_cli(
            work,
            &[
                "-c",
                "user.email=t@t",
                "-c",
                "user.name=t",
                "commit",
                "-q",
                "-m",
                message,
            ],
        );
    }

    /// A bare repository standing in for GitHub, with one commit on `main`.
    fn remote_at(root: &Path) -> PathBuf {
        let seed = root.join("seed");
        std::fs::create_dir_all(&seed).expect("a seed directory");
        git_cli(&seed, &["init", "-q", "-b", "main", "."]);
        std::fs::write(seed.join("README.md"), "seed\n").expect("a README");
        commit(&seed, "seed");
        let origin = root.join("origin.git");
        git_cli(root, &["clone", "-q", "--bare", "seed", "origin.git"]);
        origin
    }

    /// A workspace clone on a pushed branch, as `dl` would leave one.
    fn clone_at(remote: &Path, work: &Path, branch: &str) -> PathBuf {
        let parent = work.parent().expect("a parent directory");
        std::fs::create_dir_all(parent).expect("the parent");
        git_cli(
            parent,
            &[
                "clone",
                "-q",
                &remote.display().to_string(),
                &work.display().to_string(),
            ],
        );
        git_cli(work, &["checkout", "-q", "-b", branch]);
        std::fs::write(work.join("feature.txt"), "work\n").expect("a tracked file");
        commit(work, "feature");
        git_cli(work, &["push", "-q", "-u", "origin", branch]);
        work.to_path_buf()
    }

    fn storage_at(path: &Path) -> MetadataStorage {
        MetadataStorage::open(path).expect("a metadata store").0
    }

    fn listed(id: &str, source: serde_json::Value) -> serde_json::Value {
        serde_json::json!({
            "id": id,
            "source": source,
            "lastUsed": "2026-01-01T00:00:00+0000",
            "provider": { "name": "docker" },
            "ide": { "name": "none" },
            "context": "default",
        })
    }

    /// One workspace, parsed the way devpod's listing is parsed.
    fn workspace(id: &str, source: serde_json::Value) -> Workspace {
        devpod::parse_workspaces(&serde_json::json!([listed(id, source)]).to_string())
            .expect("a listing")
            .remove(0)
    }

    fn local(path: &Path) -> serde_json::Value {
        serde_json::json!({ "localFolder": path.display().to_string() })
    }

    fn argvs_to_devpod(runner: &FakeDevpodRealGit) -> Vec<Vec<String>> {
        runner.devpod.args_to(devpod::PROGRAM)
    }

