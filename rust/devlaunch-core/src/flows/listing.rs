/// The `--ls --json` document for *rows*.
///
/// Grade A: `wf` parses this, so the field names, the camelCase, the key order and
/// which fields are null where are the contract. The document is a value rather
/// than printed text — the binary spells it, with two-space indentation as
/// Python's `json.dumps(…, indent=2)` does.
pub fn json_document(rows: &[ListedWorkspace]) -> serde_json::Value {
    serde_json::Value::Array(rows.iter().map(json_row).collect())
}

/// The nine fields every row carries, in the order the wire carries them.
///
/// A struct rather than nine inserts, so the names and the order are declared once
/// and `serde` keeps them; `disk` is not here because it is absent from the object
/// rather than null when nobody asked, which no field can be.
#[derive(Debug, Serialize)]
struct RowWire {
    id: String,
    devlaunch: bool,
    repo: Option<String>,
    branch: Option<String>,
    #[serde(rename = "checkedOut")]
    checked_out: Option<String>,
    path: Option<String>,
    state: Option<String>,
    #[serde(rename = "lastUsed")]
    last_used: String,
    unsaved: Option<serde_json::Value>,
}

fn json_row(row: &ListedWorkspace) -> serde_json::Value {
    let wire = RowWire {
        id: row.id.clone(),
        devlaunch: row.clone.is_some(),
        repo: row
            .clone
            .as_ref()
            .and_then(|clone| clone.recorded.as_ref())
            .map(Recorded::slug),
        branch: row
            .clone
            .as_ref()
            .and_then(|clone| clone.recorded.as_ref())
            .map(|recorded| recorded.branch.clone()),
        checked_out: row
            .clone
            .as_ref()
            .and_then(|clone| clone.state.branch.clone()),
        path: row
            .clone
            .as_ref()
            .map(|clone| clone.path.display().to_string()),
        state: row
            .state
            .as_ref()
            .map(|state| state.as_devpod_word().to_owned()),
        last_used: row.last_used.clone(),
        unsaved: row
            .clone
            .as_ref()
            .map(|clone| clone.state.unsaved.as_json()),
    };
    let mut value = serde_json::to_value(&wire).unwrap_or_else(|_| serde_json::json!({}));
    match &row.disk {
        // Absent unless asked, so a reader can never mistake "nobody asked" for
        // "nothing on disk".
        DiskField::NotAsked => {}
        // Null where there is no clone of dl's own, the same way `repo` and
        // `branch` already say "not mine".
        DiskField::NothingOfOurs => insert(&mut value, "disk", serde_json::Value::Null),
        DiskField::Freed(usage) => insert(&mut value, "disk", disk_usage::usage_as_json(usage)),
    }
    value
}

fn insert(object: &mut serde_json::Value, key: &str, field: serde_json::Value) {
    if let Some(map) = object.as_object_mut() {
        map.insert(key.to_owned(), field);
    }
}

