/// One `dl` command's view of devpod: the runner it asks, and the one workspace
/// listing it has been given.
///
/// Held by the binary for the length of a command and dropped with it. See the
/// module docs for why the snapshot is a value rather than a process global.
///
/// The runner is held beside the snapshot rather than passed in per call, because
/// a snapshot taken through one runner and read through another is a state worth
/// not having: the fake runner a test drives and the real one differ in exactly
/// the answer being memoized.
pub struct CommandContext<'r> {
    runner: &'r dyn Runner,
    /// `None` until devpod has answered once. Never holds an answer devpod did
    /// not give.
    snapshot: Option<Vec<Workspace>>,
}

impl<'r> CommandContext<'r> {
    /// The context one command runs in.
    pub fn new(runner: &'r dyn Runner) -> Self {
        Self {
            runner,
            snapshot: None,
        }
    }

    /// The runner every flow under this command spawns through.
    pub(crate) fn runner(&self) -> &'r dyn Runner {
        self.runner
    }

    /// The git client for this command.
    pub fn git(&self) -> Git<'r> {
        Git::new(self.runner)
    }

    /// Every workspace devpod lists, asking devpod at most once per command.
    ///
    /// A copy, as Python hands out a copy: a caller that sorts or filters its list
    /// in place must not be rewriting what the next caller sees.
    pub fn workspaces(&mut self) -> Result<Vec<Workspace>, ListingUnreadable> {
        if let Some(remembered) = &self.snapshot {
            return Ok(remembered.clone());
        }
        self.read_devpod()
    }

    /// Ask devpod again, whatever the snapshot holds.
    ///
    /// For a caller that must have the post-mutation truth even though nothing
    /// announced the mutation — Python's `list_workspaces(refresh=True)`.
    pub(crate) fn refreshed_workspaces(&mut self) -> Result<Vec<Workspace>, ListingUnreadable> {
        self.read_devpod()
    }

    /// Forget the snapshot, so a later read in this command asks devpod again.
    ///
    /// Every path that changes what devpod would list calls this — Python's
    /// `invalidate_workspace_list_cache()`. `&mut self` is the point: a flow that
    /// mutates devpod has to be handed the context mutably, so it cannot quietly
    /// leave a stale snapshot behind a shared reference.
    pub(crate) fn forget_workspaces(&mut self) {
        self.snapshot = None;
    }

    /// The workspace ids, for completion.
    ///
    /// Held for the #251 §7 public-API freeze — the `list` verb's id-only form.
    /// Only this module's tests ask today; the binary reads the whole listing.
    #[cfg_attr(not(test), allow(dead_code))]
    pub(crate) fn workspace_ids(&mut self) -> Result<Vec<String>, ListingUnreadable> {
        Ok(self
            .workspaces()?
            .into_iter()
            .map(|workspace| workspace.id)
            .collect())
    }

    fn read_devpod(&mut self) -> Result<Vec<Workspace>, ListingUnreadable> {
        let workspaces = devpod::list_workspaces(self.runner)?;
        self.snapshot = Some(workspaces.clone());
        Ok(workspaces)
    }
}

