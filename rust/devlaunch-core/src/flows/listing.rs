/// Whether *workspace* is one devlaunch made, rather than someone else's.
///
/// devpod's workspace namespace is shared: `devpod up` by hand, another tool and
/// an older devlaunch all land in the same list, and devlaunch has no business
/// destroying any of them. The question this answers is the narrow one — *did I
/// make this* — and it is answered from where the workspace's source lives.
///
/// Every workspace `dl owner/repo[@branch]` creates is a clone devlaunch put
/// under its own cache directory (`<cache>/repos/<owner>/<repo>/<id>`) and then
/// handed to `devpod up` as a path, so devpod records that path as the source.
/// That makes the predicate say something true of `--purge` rather than merely
/// correlated with it: the cache directory is exactly what a purge removes, so the
/// workspaces it deletes are the ones whose source it is about to delete anyway.
/// Anything else keeps working afterwards, because nothing a purge touches backs
/// it.
///
/// Chosen over reading `metadata.json`, which also records these ids, for two
/// reasons. `metadata.json` lives *inside* the cache directory a purge removes,
/// and a purge only warns when `devpod delete` fails — so one failed delete plus
/// one successful purge would leave a workspace no later purge could ever
/// recognise. And the record is append-mostly: nothing prunes it, so it
/// accumulates entries for workspaces that are long gone. A source path is read
/// back from devpod itself every time, and survives the cache it names.
///
/// Deliberately conservative in two places. A git or unrecognised source is never
/// ours: devlaunch always passes devpod a local path. And the comparison is a
/// path containment test, not a string prefix — `<cache>-scratch` shares six
/// characters with `<cache>` and is not inside it, which
/// [`Path::starts_with`]'s component-wise comparison is what gives for free.
///
/// Not every workspace dl creates is recognised, but every *clone* it makes is.
/// `dl ./path` and `dl <git-url>` open a source dl did not clone and does not
/// record anywhere, so those read as someone else's: that is the safe direction
/// to be wrong in, it keeps this predicate and what a purge actually destroys
/// answering to the same directory, and `--purge` names what it leaves rather
/// than passing over it in silence.
///
/// **The containment test is complete for dl's own clones**, which is what makes
/// one predicate enough. A clone's directory is
/// [`clone_root_in`](crate::domain::xdg::clone_root_in) of the cache directory
/// plus owner, repo and id, so it is inside `cache_dir` by construction. It was
/// not always: `config.toml` could name a `repos_dir` outside the cache, and a
/// clone there answered `false` here — taking `devlaunch`, `SIZE` and `unsaved`
/// out together and leaving a tree `--purge` and `--prune` both scanned past.
/// Retiring that key (#467) removed the case rather than adding a second
/// predicate to cover it. Complete *for a given cache home*: a moved
/// `XDG_CACHE_HOME` strands what the old one held, as it does for any tool that
/// respects it.
pub(crate) fn is_devlaunch_clone(workspace: &Workspace, cache_dir: &Path) -> bool {
    match &workspace.source {
        // Purely lexical, so a clone whose directory has already been removed is
        // still recognisable from the source devpod kept.
        WorkspaceSource::LocalFolder(path) => {
            let path = Path::new(path);
            path != cache_dir && path.starts_with(cache_dir)
        }
        WorkspaceSource::GitRepository(_)
        | WorkspaceSource::UnreadableLocalFolder(_)
        | WorkspaceSource::Unrecognised(_) => false,
    }
}

/// Devlaunch's own clone directory for *workspace*, or nothing when it has none.
///
/// Where the boundary "is this dl's to touch?" is kept, for every surface that
/// needs it. `--ls --size` and the table's `SIZE` column walk it, and a
/// `--ls --json` row derives three more fields from this one answer: whether
/// there is a clone of dl's, which directory, and what is in it. Asking once is
/// what stops those from disagreeing about the same workspace — `disk` and then
/// `unsaved` each used to ask a question of their own and each came apart from
/// its neighbours in turn (devlaunch#165, then #171).
///
/// Only devlaunch's own clones. `dl ./path` opens somebody's project directory
/// and `dl <url>` opens a source devlaunch never cloned; walking either would put
/// an unbounded stat of a stranger's tree behind a listing command, the bytes
/// would not be devlaunch's disk in any case, and dl has no business reporting on
/// the state of a checkout it did not make.
///
/// Ownership is the same predicate `--purge` deletes by, not the presence of a
/// metadata record. A record can be missing from a cache that is very much on
/// disk, and a workspace dl reports as its own must not then be reported as
/// unmeasurable — the disk it would free is the same either way.
pub(crate) fn measurable_clone(workspace: &Workspace, cache_dir: &Path) -> Option<PathBuf> {
    match &workspace.source {
        WorkspaceSource::LocalFolder(path) if is_devlaunch_clone(workspace, cache_dir) => {
            Some(PathBuf::from(path))
        }
        _ => None,
    }
}

/// A `devpod list` answer split by whether devlaunch created each workspace.
///
/// A value rather than a filter applied at the point of deletion: `--purge`
/// prints a count and then deletes a set, and those two cannot disagree if they
/// read the same object. It also gives the workspaces devlaunch does *not* own
/// somewhere to be named from, which is the difference between a purge that
/// surprises a user with survivors and one that lists them.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
// binary surface — not part of the frozen wf API (#251 §7)
pub struct WorkspaceOwnership {
    pub mine: Vec<Workspace>,
    pub foreign: Vec<Workspace>,
}

/// Split *workspaces* into the ones devlaunch made and the ones it did not.
///
/// Total: every workspace lands in exactly one arm, and listing order is kept
/// within each, so what is printed reads in the order devpod gave.
pub(crate) fn workspace_ownership(
    workspaces: &[Workspace],
    cache_dir: &Path,
) -> WorkspaceOwnership {
    let mut split = WorkspaceOwnership::default();
    for workspace in workspaces {
        // One pass, so the predicate is asked once per workspace and the two arms
        // cannot be built from two different answers to the same question.
        if is_devlaunch_clone(workspace, cache_dir) {
            split.mine.push(workspace.clone());
        } else {
            split.foreign.push(workspace.clone());
        }
    }
    split
}

