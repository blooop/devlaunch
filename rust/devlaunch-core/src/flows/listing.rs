/// The `SIZE` cell of one table row.
///
/// Three arms for the reason [`DiskField`] has three: an unasked-for column is a
/// fact about the table, and nothing-measured is a fact about a workspace. A
/// workspace devlaunch did not make reads as `-` rather than `0 B` — nothing was
/// measured there, and a zero would say the opposite of that. The dash and the
/// empty cell are the binary's spelling.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum SizeCell {
    NoColumn,
    NotOurs,
    Measured(DiskUsage),
}

/// The `LAST USED` cell: devpod's stamp, cut to its date and time, or that there
/// is none.
///
/// The empty string devpod sends for a workspace it has never opened is an arm
/// here rather than a value, because the word standing in for it is the binary's.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum LastUsed {
    Never,
    At(String),
}

impl LastUsed {
    /// Python's `ws.last_used[:19].replace("T", " ")` — the first nineteen
    /// characters, which is `YYYY-MM-DDTHH:MM:SS`, with the `T` opened out.
    fn of(stamp: &str) -> Self {
        if stamp.is_empty() {
            return Self::Never;
        }
        Self::At(
            stamp
                .chars()
                .take(19)
                .map(|character| if character == 'T' { ' ' } else { character })
                .collect(),
        )
    }
}

/// One row of `dl --ls`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TableRow {
    pub id: String,
    pub source: SourceDescription,
    pub size: SizeCell,
    pub last_used: LastUsed,
}

/// What `dl --ls` has to show.
///
/// A machine with no workspaces is its own arm rather than an empty list of rows:
/// it prints one sentence instead of a header over nothing, and the column widths
/// the table is laid out from are maxima over the rows, which an empty list has
/// none of.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum WorkspaceTable {
    Nothing,
    Rows(NonEmpty<TableRow>),
}

/// The `dl --ls` table's content: one row per workspace, sizes if asked for.
///
/// Each source is described once, so the widths the binary measures are measured
/// on the same strings it prints — sizes included, which is also why the walk
/// happens here and not again at print time.
pub fn workspace_table(
    context: &mut CommandContext<'_>,
    cache_dir: &Path,
    sizes: Sizes,
) -> Result<WorkspaceTable, ListingUnreadable> {
    let workspaces = context.workspaces()?;
    let rows = workspaces.iter().map(|workspace| TableRow {
        id: workspace.id.clone(),
        source: describe_source(&workspace.source),
        size: size_cell(workspace, cache_dir, sizes),
        last_used: LastUsed::of(&workspace.last_used),
    });
    Ok(match NonEmpty::of(rows) {
        None => WorkspaceTable::Nothing,
        Some(rows) => WorkspaceTable::Rows(rows),
    })
}

fn size_cell(workspace: &Workspace, cache_dir: &Path, sizes: Sizes) -> SizeCell {
    match DiskField::of(sizes, measurable_clone(workspace, cache_dir).as_deref()) {
        DiskField::NotAsked => SizeCell::NoColumn,
        DiskField::NothingOfOurs => SizeCell::NotOurs,
        DiskField::Freed(usage) => SizeCell::Measured(usage),
    }
}

