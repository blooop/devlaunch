//! What exists: the workspace list, who made each one, and what it holds.
//!
//! Everything behind `dl --ls` and `dl --ls --json`, plus the two questions the
//! completion cache asks of the same reading (which repos are known, which
//! workspace ids exist). Ported from `dl.py`'s `list_workspaces`,
//! `get_workspace_ids`, `describe_source`, `is_devlaunch_clone`,
//! `_measurable_clone`, `workspace_ownership`, `discover_repos_from_workspaces`,
//! `get_known_repos`, `_unsaved_work_in`, `workspaces_as_json` and
//! `print_workspaces`; see docs/rust-rewrite-plan.md (M5).
//!
//! # One `devpod list` per command, owned by a value
//!
//! `devpod list --output json` costs ~0.45s — five times the whole of Python's
//! startup — and six call sites read it, so `dl --purge` used to spend ~0.9s
//! asking the same question twice. Python memoized it in a module-level dict and
//! had every mutating path call `invalidate_workspace_list_cache()`; `main()`
//! cleared it on the way in so a second `main()` in one process could not be
//! served the first command's view of devpod.
//!
//! That last sentence is the whole design, and it is a statement about *one
//! command*, not about the process. So the snapshot lives in
//! [`CommandContext`] — a value the binary makes one of per command — instead of
//! in a global that has to be reset. The reset is then structural: a context that
//! was never built cannot hold a stale answer, and a test driving two commands
//! builds two contexts rather than remembering to clear one.
//!
//! Two distinctions the snapshot keeps, both of which a plainer memo loses:
//!
//! - **"nothing read yet" is not "devpod has no workspaces."** The first is
//!   `None`, the second is `Some(vec![])`. Collapsing them would make a real
//!   empty answer be re-read on every call.
//! - **Only an answer devpod actually gave is remembered.** A read that failed or
//!   could not be parsed answers [`ListingUnreadable`] and stores nothing, so
//!   neither a transient failure nor a missing devpod is ever served to a later
//!   caller as "this machine has no workspaces", and the next call asks devpod
//!   again.
//!
//! # The `--ls --json` document is a wire format
//!
//! `wf` parses it (`wf reap`, and the picker's background survey), so the field
//! names, the camelCase, the key order and which fields are null where are a
//! contract and not a rendering choice. [`json_document`] is the one place it is
//! spelled, and the goldens behind its tests were generated by running the Python
//! against the fake-devpod shim rather than read off this file.
//!
//! The two fields that carry the design are `unsaved` and `disk`, and they carry
//! it the same way: a one-key object, where the key says which kind of answer it
//! is. `null` then keeps exactly one meaning — *there is no clone of dl's own
//! here to inspect* — which is why this module models a row's dl-side half as
//! [`Option<DevlaunchClone>`] rather than as a `devlaunch: bool` beside four
//! fields that have to agree with it. Python's `workspaces_as_json` docstring is
//! two paragraphs of prose about keeping them in agreement, and its history is
//! two shipped bugs (devlaunch#165, then #171) where they came apart; here
//! "`unsaved: null` iff `devlaunch: false`" is one `Option` and cannot come
//! apart.

