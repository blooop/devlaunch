    /// devpod from the fake, everything else from real processes.
    ///
    /// The shim's arrangement, in-process: git has to be real here for the same
    /// reason `domain::workspace_state`'s tests need it — the answers this module
    /// splices into `unsaved` and `checkedOut` come out of a real repository, and
    /// a faked git would only prove this file agrees with itself.
    struct FakeDevpodRealGit {
        devpod: FakeRunner,
        processes: ProcessRunner,
        /// See [`timing::exclusive`]. Last field, so it is dropped last.
        _serialized: timing::Exclusive,
    }

    impl FakeDevpodRealGit {
        /// The runner, and the timing exclusion for as long as it lives.
        ///
        /// [`container_state`] opens the `devpod-up` stage on the **process-global**
        /// registry, once per row — so an enriched listing built without the guard
        /// writes into whatever document a concurrent measured test installed, and
        /// its stage guard closes a stage that test opened rather than one of its
        /// own. In the fixture rather than per test, as `lifecycle`'s `Devpod` and
        /// `launch`'s `Scene` do it, so a new test cannot forget.
        fn new() -> Self {
            Self {
                devpod: FakeRunner::new(),
                processes: ProcessRunner,
                _serialized: timing::exclusive(),
            }
        }

        fn is_devpod(spec: &SpawnSpec) -> bool {
            spec.invocation.program == devpod::PROGRAM
        }
    }

    impl Runner for FakeDevpodRealGit {
        fn capture(&self, spec: &SpawnSpec) -> Outcome<CapturedText> {
            if Self::is_devpod(spec) {
                self.devpod.capture(spec)
            } else {
                self.processes.capture(spec)
            }
        }

        fn passthrough(&self, spec: &SpawnSpec) -> Outcome {
            if Self::is_devpod(spec) {
                self.devpod.passthrough(spec)
            } else {
                self.processes.passthrough(spec)
            }
        }

        fn session(&self, spec: &SpawnSpec, on_stderr_line: &mut dyn FnMut(&str)) -> Outcome {
            if Self::is_devpod(spec) {
                self.devpod.session(spec, on_stderr_line)
            } else {
                self.processes.session(spec, on_stderr_line)
            }
        }

        fn detach(&self, what: &Invocation) -> DetachOutcome {
            if what.program == devpod::PROGRAM {
                self.devpod.detach(what)
            } else {
                self.processes.detach(what)
            }
        }
    }

    /// The recorded path when it is usable, the derivation otherwise.
    ///
    /// Stands in for `flows::workspace_clone`'s `resolve_clone_path`, which is the
    /// production implementation of [`ClonePathResolver`] and lands with the clone
    /// manager. The rule is Python's, and both halves of it are load-bearing:
    /// *usable* means absolute (an empty recorded path is `Path(".")` in Python,
    /// which is truthy and exists, and once sent `rmtree` at dl's own working
    /// directory) and not established-absent (a path dl was not allowed to stat is
    /// not a path it has established the absence of, so it keeps the record rather
    /// than deriving a different directory).
    struct RecordedOrDerived {
        repos_dir: PathBuf,
    }

    impl ClonePathResolver for RecordedOrDerived {
        fn clone_path(&self, record: &WorktreeInfo) -> Option<PathBuf> {
            let recorded = &record.local_path;
            if recorded.is_absolute() && !established_absent(recorded) {
                return Some(recorded.clone());
            }
            let id = WorkspaceId::new(&record.owner, &record.repo, &record.branch).ok()?;
            Some(
                self.repos_dir
                    .join(&record.owner)
                    .join(&record.repo)
                    .join(id.value()),
            )
        }
    }

    fn established_absent(path: &Path) -> bool {
        matches!(
            std::fs::symlink_metadata(path),
            Err(error)
                if matches!(
                    error.kind(),
                    std::io::ErrorKind::NotFound | std::io::ErrorKind::NotADirectory
                )
        )
    }

    /// A resolver that can never name a directory — the `None` arm every caller
    /// has to treat as a refusal.
    struct NamesNothing;

    impl ClonePathResolver for NamesNothing {
        fn clone_path(&self, _record: &WorktreeInfo) -> Option<PathBuf> {
            None
        }
    }

