/// Names the one directory a metadata record's clone lives in.
///
/// The listing, the `dl <ws> rm` guard and the delete itself all have to name the
/// *same* directory — they used to name it separately and could disagree
/// (devlaunch#174), with the guard clearing an absent directory while the delete
/// removed the one holding the work. So there is one function that names it, it
/// lives with the clones (`flows::workspace_clone`), and this is the seam the
/// listing reads it through rather than a second copy of the rule.
///
/// `None` means dl cannot name a directory for this record at all: the recorded
/// path is unusable *and* the derivation refuses the record's own
/// owner/repo/branch. Every caller treats that as a refusal rather than as an
/// empty answer.
pub trait ClonePathResolver {
    fn clone_path(&self, record: &WorktreeInfo) -> Option<PathBuf>;
}

/// Everything the enriched listing reads besides devpod.
pub struct DlView<'a> {
    /// Where devlaunch keeps its own clones — the directory `--purge` removes and
    /// ownership is decided by.
    pub cache_dir: &'a Path,
    pub storage: &'a MetadataStorage,
    pub clones: &'a dyn ClonePathResolver,
}

/// Whether `--size` was asked for.
///
/// A named pair rather than a bool at the call sites, because it decides whether
/// a `disk` field exists at all — see [`DiskField`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Sizes {
    Skip,
    Measure,
}

/// The `repo` and `branch` a workspace was made for, from the record dl wrote.
///
/// One value rather than two nullable fields, because they are absent together:
/// a clone under the cache that dl has no record for — a metadata write that
/// failed, a record pruned, a cache restored without one — has neither.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct Recorded {
    pub(crate) owner: String,
    pub(crate) repo: String,
    /// What the workspace was made for. The clone's current HEAD can differ (an
    /// agent checked something else out), which is why both are reported and
    /// neither stands for the other.
    pub(crate) branch: String,
}

impl Recorded {
    fn of(record: &WorktreeInfo) -> Self {
        Self {
            owner: record.owner.clone(),
            repo: record.repo.clone(),
            branch: record.branch.clone(),
        }
    }

    /// The `owner/repo` slug the wire calls `repo`.
    pub(crate) fn slug(&self) -> String {
        format!("{}/{}", self.owner, self.repo)
    }
}

/// A clone devlaunch made, and everything the row says about it.
///
/// Its presence *is* the `devlaunch: true` of the wire format. Python carried
/// that as a bool beside `repo`, `branch`, `path`, `checkedOut` and `unsaved`,
/// each of which had to be null exactly when the bool was false — a correlation
/// its docstring spends two paragraphs on and whose history is two shipped bugs.
/// Here the fields exist only inside this arm, so the correlation is the type.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct DevlaunchClone {
    /// The directory `unsaved` and `checkedOut` describe, and the one
    /// `dl <ws> rm` would act on.
    ///
    /// A record moves the row onto the recorded directory, because that is the one
    /// the delete's guard reads and a listing describing a different directory
    /// from the guard would be worse than useless to the caller deciding whether
    /// to call it.
    pub(crate) path: PathBuf,
    pub(crate) recorded: Option<Recorded>,
    pub(crate) state: CloneState,
}

/// The `disk` field: absent unless `--size` was asked for, null where dl has no
/// clone of its own to measure, and otherwise what deleting that clone would
/// free.
///
/// Three arms, because "nobody asked" and "nothing of dl's is here" are different
/// facts and a reader must not be able to mistake one for the other. Python keeps
/// the same distinction with an absent key versus a `null` one, and its comment
/// on the table's `SIZE` column says why in as many words: *"there is no column"
/// is a fact about the table and "nothing was measured" is a fact about a
/// workspace*.
///
/// The measurement is of the clone the *source path* names, which a metadata
/// record cannot move — the same set of workspaces the table's `SIZE` column
/// measures, by construction rather than by two gates agreeing (devlaunch#165).
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) enum DiskField {
    NotAsked,
    NothingOfOurs,
    Freed(DiskUsage),
}

impl DiskField {
    fn of(sizes: Sizes, measurable: Option<&Path>) -> Self {
        match (sizes, measurable) {
            (Sizes::Skip, _) => Self::NotAsked,
            (Sizes::Measure, None) => Self::NothingOfOurs,
            (Sizes::Measure, Some(clone)) => Self::Freed(disk_usage::exclusive_usage(clone)),
        }
    }
}

/// One workspace, as `dl --ls --json` reports it.
///
/// Every field is something dl can answer for certain. `state` is devpod's, one
/// `devpod status` per workspace, which is why this is a command someone runs
/// rather than something on the fast path.
///
/// # One correlation left representable, deliberately
///
/// [`DiskField::Freed`] beside `clone: None` is a state this type permits and
/// [`enriched_row`] cannot build: both are derived from the one
/// [`measurable_clone`] answer, which is the whole point of asking it once. Typing
/// it out would mean moving `disk` inside [`DevlaunchClone`] — and that loses the
/// distinction the field exists for, because a workspace that is *not* dl's still
/// has to carry `disk: null` under `--size`. Whether anybody asked is a fact about
/// the document; whether there is a clone to measure is a fact about the row; and
/// the three-armed [`DiskField`] is the flattest shape that says both.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ListedWorkspace {
    pub(crate) id: String,
    /// devpod's `lastUsed`, verbatim.
    pub(crate) last_used: String,
    /// devpod's container state, or nothing when `devpod status` would not answer.
    pub(crate) state: Option<ContainerState>,
    /// `None` for a workspace devlaunch did not make: there is no clone of dl's
    /// own here to inspect, and dl has no business inspecting someone else's
    /// checkout to find one.
    pub(crate) clone: Option<DevlaunchClone>,
    pub(crate) disk: DiskField,
}

/// The enriched listing: one row per workspace devpod lists, in devpod's order.
///
/// Costs one `devpod list` (the command's snapshot) plus one `devpod status` per
/// listed workspace — including the ones devlaunch did not make, which Python asks
/// about too. Under [`Sizes::Measure`] it also walks each of dl's own clones,
/// which is O(files) with no ceiling and the reason `--size` is asked for rather
/// than always answered.
pub fn enriched_listing(
    context: &mut CommandContext<'_>,
    view: &DlView<'_>,
    sizes: Sizes,
) -> Result<Vec<ListedWorkspace>, ListingUnreadable> {
    let workspaces = context.workspaces()?;
    let git = context.git();
    let runner = context.runner();
    Ok(workspaces
        .iter()
        .map(|workspace| enriched_row(runner, &git, view, sizes, workspace))
        .collect())
}

fn enriched_row(
    runner: &dyn Runner,
    git: &Git<'_>,
    view: &DlView<'_>,
    sizes: Sizes,
    workspace: &Workspace,
) -> ListedWorkspace {
    // One question asked once. Whether this workspace is dl's, which directory the
    // row is about, and what is in it all read this answer, rather than each
    // asking a question of its own — which is how `disk` and then `unsaved` came
    // apart from their neighbours in turn (devlaunch#165, then #171).
    let measurable = measurable_clone(workspace, view.cache_dir);
    let clone = measurable.as_ref().map(|measured| {
        // There is no record to read unless the workspace is already dl's, so a
        // leftover record cannot make a foreign workspace dl's own.
        let record = view.storage.get_worktree_by_workspace_id(&workspace.id);
        // Resolved, not read straight off the record: this has to be the directory
        // the delete will remove, and those were two answers (devlaunch#174).
        // Keeping the measured clone when the resolver cannot name one is what
        // holds the row's own invariant — a row that has already said the clone is
        // dl's must not then say there is none.
        let path = record
            .and_then(|record| view.clones.clone_path(record))
            .unwrap_or_else(|| measured.clone());
        DevlaunchClone {
            state: workspace_state::read_clone(git, &path),
            path,
            recorded: record.map(Recorded::of),
        }
    });
    ListedWorkspace {
        id: workspace.id.clone(),
        last_used: workspace.last_used.clone(),
        state: container_state(runner, &workspace.id),
        clone,
        disk: DiskField::of(sizes, measurable.as_deref()),
    }
}

/// devpod's state for one workspace, or nothing when it would not answer.
///
/// Python collapses every unreadable answer to `None` and the wire field is `null`
/// for all of them: a devpod that refused the question, output that was not JSON,
/// and JSON with no `state` in it. The distinctions exist one layer down
/// ([`devpod::StatusUnreadable`]) for a caller that has something different to do
/// about each; this one does not.
fn container_state(runner: &dyn Runner, workspace_id: &str) -> Option<ContainerState> {
    // Staged, because Python stages `get_workspace_state` itself
    // (`@timing.staged("devpod-up")`), and the JSON timing document reports spans
    // *inside* the stage that was open. Unstaged, the `devpod status` round trips
    // this makes are in the prose summary and missing from the document — which is
    // the shape a listing of five workspaces reports the most of.
    let mut stage = timing::stage(timing::Stage::DevpodUp);
    let answer = devpod::status(runner, workspace_id);
    // Python stages `get_workspace_state`, which returns `None` (stage `ok`) for a
    // devpod that ran and refused, gave non-JSON, or omitted `state`, and only
    // marks the stage `failed` when devpod could not be run at all — the spawn
    // that raises `DevpodNotInstalled`. Mirror that: a `NotRun` fails the stage so
    // the timing document does not report `ok` for a step devpod never ran (P12).
    if matches!(answer, Err(devpod::StatusUnreadable::NotRun(_))) {
        stage.fail();
    }
    answer.ok()
}

/// What deleting *workspace_id* would destroy, as far as dl can establish.
///
/// The `dl <ws> rm` guard's reader. Answers [`Unsaved::NothingToLose`] for a
/// workspace devlaunch has no record of, which is the honest answer rather than a
/// permissive one: those are workspaces opened from a path or a URL that dl never
/// cloned and does not manage, so it has no clone of its own to protect and no
/// business inspecting somebody's checkout to find one.
///
/// A record dl cannot turn into a directory is a different matter and gets a
/// different answer (devlaunch#171): dl does not know where the clone is, so it
/// has not established that anything is safe, and the delete stops until somebody
/// says `--force`.
///
/// Python has a third arm here, for a record it could not *read* — an `OSError`
/// or `RuntimeError` out of the metadata load, answered as
/// [`Unsaved::CouldNotTell`]. It has no analogue because it cannot be reached from
/// this signature: a [`MetadataStorage`] exists only if it was opened, and an open
/// that failed is a typed error its caller already has to handle. The refusal
/// moved earlier; it did not disappear.
pub(crate) fn unsaved_work_in(git: &Git<'_>, view: &DlView<'_>, workspace_id: &str) -> Unsaved {
    let Some(record) = view.storage.get_worktree_by_workspace_id(workspace_id) else {
        return Unsaved::NothingToLose;
    };
    match view.clones.clone_path(record) {
        Some(clone) => workspace_state::holds_unsaved_work(git, &clone),
        None => Unsaved::CouldNotTell(CouldNotTell::DirectoryUnknown {
            workspace_id: workspace_id.to_owned(),
        }),
    }
}

