    /// The four kinds of row, on one machine.
    struct Scene {
        /// Held for its `Drop`: the whole world below lives under it.
        _root: tempfile::TempDir,
        cache: PathBuf,
        runner: FakeDevpodRealGit,
        storage: MetadataStorage,
        resolver: RecordedOrDerived,
        clean: PathBuf,
        dirty: PathBuf,
        unrecorded: PathBuf,
        ids: BTreeMap<&'static str, String>,
    }

    impl Scene {
        /// One dl-made workspace with a clean clone and a record, one with unsaved
        /// work and a record, one dl clone with no record, and two workspaces dl
        /// did not make (a folder of somebody's, and a source with no folder).
        fn build() -> Self {
            let root = temp_dir();
            let cache = cache_dir_for(root.path());
            let repos = cache.join("repos");
            let remote = remote_at(root.path());

            let clean_id = WorkspaceId::new("blooop", "demo", "feature")
                .expect("a safe triple")
                .value();
            let dirty_id = WorkspaceId::new("blooop", "demo", "messy")
                .expect("a safe triple")
                .value();
            let unrecorded_id = WorkspaceId::new("blooop", "other", "main")
                .expect("a safe triple")
                .value();
            // The ids the Python run produced, so the fixture and the goldens are
            // known to be about the same workspaces.
            assert_eq!(clean_id, "demo-feature-j53q");
            assert_eq!(dirty_id, "demo-messy-valn");
            assert_eq!(unrecorded_id, "other-main-tcyo");

            let clean = clone_at(
                &remote,
                &repos.join("blooop/demo").join(&clean_id),
                "feature",
            );
            let dirty = clone_at(&remote, &repos.join("blooop/demo").join(&dirty_id), "messy");
            std::fs::write(dirty.join("an-hour-of-work.md"), "half a plan\n")
                .expect("unsaved work");
            let unrecorded = clone_at(
                &remote,
                &repos.join("blooop/other").join(&unrecorded_id),
                "main2",
            );
            let foreign = root.path().join("projects").join("someone-elses");
            std::fs::create_dir_all(&foreign).expect("somebody else's directory");

            let mut storage = storage_at(&cache.join("metadata.json"));
            storage
                .add_worktree(WorktreeInfo::new(
                    "blooop",
                    "demo",
                    "feature",
                    clean.clone(),
                    &clean_id,
                ))
                .expect("a record");
            storage
                .add_worktree(WorktreeInfo::new(
                    "blooop",
                    "demo",
                    "messy",
                    dirty.clone(),
                    &dirty_id,
                ))
                .expect("a record");

            let runner = FakeDevpodRealGit::new();
            runner.devpod.add_workspace_from(
                &clean_id,
                &clean.display().to_string(),
                WorkspaceState::Stopped,
            );
            runner.devpod.add_workspace_from(
                &dirty_id,
                &dirty.display().to_string(),
                WorkspaceState::Running,
            );
            runner.devpod.add_workspace_from(
                &unrecorded_id,
                &unrecorded.display().to_string(),
                WorkspaceState::Stopped,
            );
            runner.devpod.add_workspace_from(
                "someone-elses",
                &foreign.display().to_string(),
                WorkspaceState::Stopped,
            );
            runner.devpod.add_workspace_from(
                "from-an-image",
                "ubuntu:24.04",
                WorkspaceState::Stopped,
            );

            let ids = BTreeMap::from([
                ("clean", clean_id),
                ("dirty", dirty_id),
                ("unrecorded", unrecorded_id),
            ]);
            Self {
                resolver: RecordedOrDerived { repos_dir: repos },
                cache,
                _root: root,
                runner,
                storage,
                clean,
                dirty,
                unrecorded,
                ids,
            }
        }

        fn view(&self) -> DlView<'_> {
            DlView {
                cache_dir: &self.cache,
                storage: &self.storage,
                clones: &self.resolver,
            }
        }

        fn rows(&self, sizes: Sizes) -> Vec<ListedWorkspace> {
            let mut context = CommandContext::new(&self.runner);
            enriched_listing(&mut context, &self.view(), sizes).expect("a listing")
        }

        fn id(&self, which: &str) -> &str {
            &self.ids[which]
        }
    }

