/// Which kind of thing a workspace opens, as `dl --ls`'s `TYPE` column names it.
///
/// The three words are a vocabulary rather than prose — they are compared by
/// tests and read by people scanning a column — so they live beside the arm they
/// belong to, the way [`ContainerState::as_devpod_word`] does.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SourceKind {
    Local,
    Git,
    /// devlaunch cannot read this source. The detail beside it is devpod's own
    /// object, which is a debug rendering and is meant to be: the listing's job is
    /// to put the row on screen rather than pass over it, and devlaunch has
    /// nothing truer to say about it.
    Unknown,
}

impl SourceKind {
    pub fn word(self) -> &'static str {
        match self {
            Self::Local => "local",
            Self::Git => "git",
            Self::Unknown => "unknown",
        }
    }
}

/// How a source reads in `dl --ls` and in the fuzzy picker.
///
/// One value for both columns and one function for both callers, so the kind
/// shown and the detail shown cannot come from two different readings of the same
/// source — which is what a tag beside a parallel field allowed.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SourceDescription {
    pub kind: SourceKind,
    pub detail: String,
}

/// [`SourceDescription`] for one source. Total over the arms.
///
/// binary surface — not part of the frozen wf API (#251 §7)
pub fn describe_source(source: &WorkspaceSource) -> SourceDescription {
    let (kind, detail) = match source {
        WorkspaceSource::LocalFolder(path) => (SourceKind::Local, path.clone()),
        WorkspaceSource::GitRepository(url) => (SourceKind::Git, url.clone()),
        WorkspaceSource::UnreadableLocalFolder(payload)
        | WorkspaceSource::Unrecognised(payload) => (
            SourceKind::Unknown,
            json_as_python_writes_it(&serde_json::Value::Object(payload.clone())),
        ),
    };
    SourceDescription { kind, detail }
}

/// Whose repository a workspace opens, when its source says.
///
/// The fuzzy picker's first column. Owner is not part of a workspace id — that is
/// `<repo-slug>-<ref-slug>-<suffix>` and carries no owner at all — so a list of
/// workspaces drawn from ids alone cannot tell `blooop/devlaunch` from a fork of
/// it, which is exactly the distinction someone scanning the picker is making.
///
/// Read from the source devpod already reported and the cache directory the
/// command already resolved, and from nothing else: no `metadata.json`, no
/// config, no disk. `metadata.json` records the owner outright and would be the
/// obvious place to ask, which is exactly what this avoids — a launch that never
/// needed the records must be shown never to have opened them (devlaunch#145),
/// and a column in the picker is not a reason to open them.
///
/// Two readings, one per arm that can carry an owner:
///
/// - A git source is read off its URL, the same three GitHub spellings
///   [`parse_owner_repo_from_url`] recognises everywhere else.
/// - A local folder is read as dl's own clone layout,
///   `<cache>/repos/<owner>/<repo>/<workspace id>` — but only for a directory
///   [`is_devlaunch_clone`] already places inside dl's cache, and only when its
///   leaf is named for this very workspace. Both guards earn their keep, because
///   a path three components deep is not on its own evidence of anything: without
///   the containment test `dl ~/dev/myproject` — whose devpod id *is* `myproject`,
///   so the leaf matches — reads as an owner called `dev`, and without the leaf
///   test any directory a user keeps under the cache would too.
///
/// `None` for everything else, the conservative direction: a workspace whose owner
/// dl cannot establish shows no owner, rather than showing a path component that
/// happens to sit where an owner would.
///
/// This reading is complete for dl's own clones and does not need the config to
/// be. `config.toml` used to be able to put them outside the cache directory
/// (`worktree.repos_dir`), which cost those rows their owner — the same blind
/// spot, from the same containment test, that `--purge` and the `SIZE` column
/// had. That key is retired (#467) and the clone root is derived from the cache
/// directory, so the picker needs no config read to be right about them.
///
/// Owned, like [`describe_source`] beside it, rather than borrowed from the
/// workspace: it keeps the signature free of lifetime plumbing for one short
/// string per row of a picker that is about to draw a terminal.
///
/// binary surface — not part of the frozen wf API (#251 §7)
pub fn owner_of(workspace: &Workspace, cache_dir: &Path) -> Option<String> {
    match &workspace.source {
        WorkspaceSource::GitRepository(url) => {
            parse_owner_repo_from_url(url).map(|(owner, _repo)| owner.to_owned())
        }
        // The guards live in `layout_of_clone`, so a local folder that is not one of
        // dl's clones answers `None` there rather than here.
        WorkspaceSource::LocalFolder(_) => {
            layout_of_clone(workspace, cache_dir).map(|(owner, _repo)| owner)
        }
        WorkspaceSource::UnreadableLocalFolder(_) | WorkspaceSource::Unrecognised(_) => None,
    }
}

/// The repo a workspace is a clone of, as dl's own layout names it.
///
/// Only ever answered for a clone dl made, and for the same reason [`owner_of`]
/// only reads an owner out of one: the name lives in the path
/// `<cache>/repos/<owner>/<repo>/<id>`, which is the only place devpod's own answer
/// carries it. The same guards apply, because both questions are now answered by
/// the one reading in [`layout_of_clone`] — so a directory merely *shaped* like the
/// layout names no repo.
///
/// **A git source answers `None` even though its URL names a repo.** A workspace
/// dl did not clone was named by
/// [`source_workspace_id`](crate::domain::workspace_id), which hashes a source with
/// no ref in it at all — so [`head_branch_of`] has nothing to answer for it either,
/// and a repo on its own would be half a reading.
///
/// The *directory* and not the id's prefix: the id spells `kinisi_ros` as
/// `kinisi-ros`, because [`slug`](crate::domain::workspace_id) turns `_` into `-`
/// and may cut what is left to fit — and the underscore is the repository's real
/// name.
///
/// binary surface — not part of the frozen wf API (#251 §7)
pub fn repo_of(workspace: &Workspace, cache_dir: &Path) -> Option<String> {
    layout_of_clone(workspace, cache_dir).map(|(_owner, repo)| repo)
}

/// The branch a workspace's clone has checked out, read from its `HEAD`.
///
/// Answered exactly when [`repo_of`] is, minus the clones that cannot say — which
/// is what makes the pair safe to ask separately: a caller wanting both takes them
/// together and treats one answer without the other as neither.
///
/// **The ref, not a slug of one.** This used to recover a label by *parsing the
/// workspace id*: strip the repo prefix, strip the identity suffix, and read what
/// was left. That answered with a slug, so `feature/auth` and `feature-auth` read
/// back alike and a long ref read back short, and it only worked because the suffix
/// had a recognisable shape. When the suffix became four characters of base 36
/// ([`SUFFIX_LENGTH`](crate::domain::workspace_id)) there was no shape left to test,
/// and the parse degraded to "assume the last four characters are the hash".
///
/// Reading `HEAD` retires all of that. It is exact, it costs one small file read
/// with no subprocess and no metadata lock, and it answers the better question: not
/// which branch the workspace was *created* for, but which one is checked out in it
/// now. Nothing reconstructs a triple from an id any more.
///
/// `None` for a detached HEAD, a clone that is gone, and a `HEAD` that cannot be
/// read. All three are cases where the id would have carried a stale label, so the
/// caller showing the whole id instead is the honest answer rather than a loss.
///
/// binary surface — not part of the frozen wf API (#251 §7)
pub fn head_branch_of(workspace: &Workspace, cache_dir: &Path) -> Option<String> {
    // The same gate `repo_of` passes, so the two still answer together: it is what
    // says this is a clone dl laid out rather than any directory devpod opened.
    layout_of_clone(workspace, cache_dir)?;
    let WorkspaceSource::LocalFolder(path) = &workspace.source else {
        return None;
    };
    head_branch(Path::new(path))
}

/// The branch named by `<clone>/.git`'s `HEAD`, or `None` if it does not name one.
///
/// Best-effort by construction: every step is a `?`, so an unreadable `.git`, a
/// missing `HEAD`, a detached one (a bare object id, with no `ref:` to strip) and a
/// symbolic ref pointing outside `refs/heads/` all answer `None` rather than
/// guessing. Nothing here runs git: `HEAD` is one line that git maintains, and a
/// subprocess per row is not worth paying to render a column.
fn head_branch(clone: &Path) -> Option<String> {
    let head = std::fs::read_to_string(git_dir(clone)?.join("HEAD")).ok()?;
    let branch = head.lines().next()?.strip_prefix("ref:")?.trim();
    non_empty(branch.strip_prefix("refs/heads/")?)
}

/// `<clone>/.git`, following a gitfile to wherever it points.
///
/// A `.git` is a directory in an ordinary clone and a *file* in a worktree or a
/// submodule, holding `gitdir: <path>`. dl's own clones are ordinary, so the file
/// case is here for the containers that are not: a repo whose devcontainer arranges
/// its checkout differently is still a workspace this column has to render. The
/// path may be relative, and it is relative to the clone.
fn git_dir(clone: &Path) -> Option<PathBuf> {
    let dot_git = clone.join(".git");
    if std::fs::metadata(&dot_git).ok()?.is_dir() {
        return Some(dot_git);
    }
    let pointed = std::fs::read_to_string(&dot_git).ok()?;
    let named = pointed.lines().next()?.strip_prefix("gitdir:")?.trim();
    let target = non_empty(named)?;
    let target = Path::new(&target);
    Some(if target.is_absolute() {
        target.to_path_buf()
    } else {
        clone.join(target)
    })
}

/// *text* unless it is empty, so "nothing was named" is one answer and not two.
fn non_empty(text: &str) -> Option<String> {
    (!text.is_empty()).then(|| text.to_owned())
}

/// dl's clone layout read backwards: the two directories above a leaf named for
/// the workspace it holds, as `(owner, repo)`.
///
/// The source has to be a local folder dl put under its cache
/// ([`is_devlaunch_clone`]), the leaf has to be named for *this* workspace, and the
/// owner directory has to be one dl put there — inside the cache and not the cache
/// itself. Without that last check a directory a user keeps *in* dl's cache, opened
/// by path, hands back whatever component sits two above its leaf:
/// `dl ~/.cache/devlaunch/scratch/myproject` would be credited to an owner called
/// `devlaunch`.
///
/// One reading for all three callers rather than one each. Every answer comes out
/// of the same three path components, so the guards cannot be applied to one
/// question and forgotten on the next — the shape of defect the id derivation was
/// rebuilt to make unrepresentable (devlaunch#55).
fn layout_of_clone(workspace: &Workspace, cache_dir: &Path) -> Option<(String, String)> {
    let WorkspaceSource::LocalFolder(path) = &workspace.source else {
        return None;
    };
    if !is_devlaunch_clone(workspace, cache_dir) {
        return None;
    }
    let path = Path::new(path);
    if path.file_name()?.to_str()? != workspace.id {
        return None;
    }
    let repo_dir = path.parent()?;
    let owner_dir = repo_dir.parent()?;
    if owner_dir == cache_dir || !owner_dir.starts_with(cache_dir) {
        return None;
    }
    Some((
        owner_dir.file_name()?.to_str()?.to_owned(),
        repo_dir.file_name()?.to_str()?.to_owned(),
    ))
}

