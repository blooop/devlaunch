    #[test]
    fn the_disk_field_and_the_size_cell_measure_the_same_set() {
        // A caller reading the JSON and a person reading the table measure the same
        // workspaces by construction (devlaunch#165), because both read
        // `measurable_clone`.
        let scene = Scene::build();
        let mut context = CommandContext::new(&scene.runner);
        let table =
            match workspace_table(&mut context, &scene.cache, Sizes::Measure).expect("a table") {
                WorkspaceTable::Rows(rows) => rows,
                WorkspaceTable::Nothing => panic!("there are workspaces"),
            };
        let rows = scene.rows(Sizes::Measure);

        let measured_in_json: Vec<bool> = rows
            .iter()
            .map(|row| matches!(row.disk, DiskField::Freed(_)))
            .collect();
        let measured_in_table: Vec<bool> = table
            .iter()
            .map(|row| matches!(row.size, SizeCell::Measured(_)))
            .collect();
        assert_eq!(measured_in_json, measured_in_table);
        assert_eq!(measured_in_json, [true, true, false, true, false]);
    }

    fn row_named<'d>(document: &'d serde_json::Value, id: &str) -> &'d serde_json::Value {
        document
            .as_array()
            .expect("an array")
            .iter()
            .find(|row| row["id"] == id)
            .unwrap_or_else(|| panic!("no row for {id}"))
    }

    fn set_mode(path: &Path, mode: u32) {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(path, std::fs::Permissions::from_mode(mode))
            .expect("the mode is settable");
    }

