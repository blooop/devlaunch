/// One workspace whose source devlaunch could not read, and what devpod said.
///
/// Carried out of [`discover_repos_from_workspaces`] rather than logged there: the
/// skip is *stated* — which is the whole of the fix — but the sentence stating it
/// is the binary's. Discovery cannot invent an owner/repo for an image reference,
/// so there is no third answer to give; what there was, before, was silence
/// indistinguishable from a source read fine and holding no repo.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct UnreadableSource {
    pub workspace_id: String,
    /// devpod's own source object, as JSON.
    pub payload: String,
}

/// Owner-to-repos, plus the workspaces whose sources could not be read.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct RepoDiscovery {
    /// Insertion-ordered, as Python's dict is; every consumer sorts.
    pub repos: IndexMap<String, Vec<String>>,
    pub unreadable: Vec<UnreadableSource>,
}

/// Discover `owner/repo` from the workspaces devpod lists.
///
/// A git source is read straight off its URL; a local folder is asked for its
/// origin remote (one `git -C <path> remote get-url origin` per local
/// workspace). Every arm is answered, including the ones devlaunch cannot read.
pub fn discover_repos_from_workspaces(git: &Git<'_>, workspaces: &[Workspace]) -> RepoDiscovery {
    let mut found = RepoDiscovery::default();
    for workspace in workspaces {
        let owner_repo = match &workspace.source {
            WorkspaceSource::GitRepository(url) => owned(parse_owner_repo_from_url(url)),
            WorkspaceSource::LocalFolder(path) => match git.origin_url_at(Path::new(path)) {
                GitAnswer::Said(url) if !url.is_empty() => owned(parse_owner_repo_from_url(&url)),
                _ => None,
            },
            WorkspaceSource::UnreadableLocalFolder(payload)
            | WorkspaceSource::Unrecognised(payload) => {
                found.unreadable.push(UnreadableSource {
                    workspace_id: workspace.id.clone(),
                    payload: json_as_python_writes_it(&serde_json::Value::Object(payload.clone())),
                });
                None
            }
        };
        if let Some((owner, repo)) = owner_repo {
            remember(&mut found.repos, owner, repo);
        }
    }
    found
}

/// Discover `owner/repo` from the bare clones under *repos_dir*.
///
/// Scans `<repos_dir>/<owner>/<repo>/.bare/` so that repos cloned locally — even
/// without a devpod workspace yet — appear in completions. Same shape as
/// [`discover_repos_from_workspaces`]'s map.
///
/// A directory it cannot read contributes nothing rather than taking the scan
/// down: completions are a convenience, and a repos directory that has become
/// unreadable is not a reason to have none.
pub(crate) fn discover_repos_from_cache_dir(repos_dir: &Path) -> IndexMap<String, Vec<String>> {
    let mut repos = IndexMap::new();
    let Ok(owners) = std::fs::read_dir(repos_dir) else {
        return repos;
    };
    for owner_entry in owners.flatten() {
        let owner_dir = owner_entry.path();
        if !owner_dir.is_dir() {
            continue;
        }
        let Ok(named) = std::fs::read_dir(&owner_dir) else {
            continue;
        };
        for repo_entry in named.flatten() {
            let repo_dir = repo_entry.path();
            if !repo_dir.is_dir() || !repo_dir.join(".bare").is_dir() {
                continue;
            }
            if let (Some(owner), Some(repo)) = (file_name(&owner_dir), file_name(&repo_dir)) {
                remember(&mut repos, owner, repo);
            }
        }
    }
    repos
}

/// The `owner/repo` strings in *repos*, sorted by owner then repo.
pub fn flatten_repos(repos: &IndexMap<String, Vec<String>>) -> Vec<String> {
    let mut owners: Vec<&String> = repos.keys().collect();
    owners.sort();
    let mut flattened = Vec::new();
    for owner in owners {
        let mut named: Vec<&String> = repos[owner].iter().collect();
        named.sort();
        for repo in named {
            flattened.push(format!("{owner}/{repo}"));
        }
    }
    flattened
}

/// The owners in *repos*, sorted.
pub(crate) fn owners_of(repos: &IndexMap<String, Vec<String>>) -> Vec<String> {
    let mut owners: Vec<String> = repos.keys().cloned().collect();
    owners.sort();
    owners
}

/// Merge *extra* into *into*, keeping insertion order and adding no duplicates.
pub(crate) fn merge_repos(
    into: &mut IndexMap<String, Vec<String>>,
    extra: &IndexMap<String, Vec<String>>,
) {
    for (owner, named) in extra {
        for repo in named {
            remember(into, owner.clone(), repo.clone());
        }
    }
}

/// The known `owner/repo` strings, from the workspaces devpod lists.
///
/// `dl --repos`' answer when there is no completion cache to read.
/// Held for the #251 §7 public-API freeze — `list`'s repository form. Only this
/// module's tests ask today; the binary reads the completion cache first.
#[cfg_attr(not(test), allow(dead_code))]
pub(crate) fn known_repos(
    context: &mut CommandContext<'_>,
) -> Result<Vec<String>, ListingUnreadable> {
    let workspaces = context.workspaces()?;
    let git = context.git();
    Ok(flatten_repos(
        &discover_repos_from_workspaces(&git, &workspaces).repos,
    ))
}

/// Extract `(owner, repo)` from a git URL, for the three GitHub spellings dl
/// recognises.
///
/// Python's three anchored regexes, hand-rolled because the shapes are fixed and
/// a regex engine is not otherwise needed here:
///
/// - `git@github.com:owner/repo[.git]`
/// - `http[s]://github.com/owner/repo[.git]`
/// - `github.com/owner/repo[.git]`
///
/// Neither half may contain a `/`, so exactly one separator is allowed after the
/// host, and a trailing `.git` is dropped only when something is left of the name
/// — `owner/.git` names a repo called `.git`, which is what Python's non-greedy
/// group settles on too.
pub(crate) fn parse_owner_repo_from_url(url: &str) -> Option<(&str, &str)> {
    // Python's `$` matches before a trailing newline, so a URL that arrived with
    // one still parses. git's own output is trimmed before it gets here; devpod's
    // is not necessarily.
    let url = url.strip_suffix('\n').unwrap_or(url);
    for prefix in [
        "git@github.com:",
        "https://github.com/",
        "http://github.com/",
    ] {
        if let Some(tail) = url.strip_prefix(prefix) {
            return split_owner_repo(tail);
        }
    }
    url.strip_prefix("github.com/").and_then(split_owner_repo)
}

/// `owner/repo[.git]` — one separator, both halves non-empty.
fn split_owner_repo(tail: &str) -> Option<(&str, &str)> {
    let (owner, repo) = tail.split_once('/')?;
    if owner.is_empty() || repo.contains('/') {
        return None;
    }
    let repo = match repo.strip_suffix(".git") {
        Some(shorter) if !shorter.is_empty() => shorter,
        _ => repo,
    };
    if repo.is_empty() {
        return None;
    }
    Some((owner, repo))
}

fn owned(pair: Option<(&str, &str)>) -> Option<(String, String)> {
    pair.map(|(owner, repo)| (owner.to_owned(), repo.to_owned()))
}

fn remember(repos: &mut IndexMap<String, Vec<String>>, owner: String, repo: String) {
    let named = repos.entry(owner).or_default();
    if !named.contains(&repo) {
        named.push(repo);
    }
}

fn file_name(path: &Path) -> Option<String> {
    Some(path.file_name()?.to_string_lossy().into_owned())
}

