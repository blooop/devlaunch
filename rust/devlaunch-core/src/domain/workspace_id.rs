//! Workspace identity: the one place a workspace id is derived.
//!
//! A workspace is identified by the triple `(owner, repo, ref)`. [`WorkspaceId`]
//! is the parsed form of that triple, and its [`value`](WorkspaceId::value) names
//! **both** the devpod workspace and the clone-directory leaf. Constructing a
//! `WorkspaceId` is the only way to derive an id from a triple, and constructing
//! one validates the triple, so no code path can reach a workspace clone
//! directory with an unvalidated ref.
//!
//! The id format is:
//!
//! ```text
//! <repo-slug>-<ref-slug>-<suffix>
//! ```
//!
//! `suffix` is eight characters of hashed identity and is never truncated.
//! `repo-slug` is the readable context and is cut to at most
//! [`REPO_SLUG_LENGTH`] characters, never shorter. `ref-slug` absorbs all
//! remaining truncation.
//!
//! **What truncation does and does not guarantee.** Only the slugs are ever
//! shortened, and the suffix is hashed over the full triple before any of that,
//! so truncating the readable part adds no collisions of its own: two triples
//! collide only when their suffixes collide. That is a birthday bound, not a
//! guarantee: distinct triples share an id with probability 2**-[`SUFFIX_BITS`]
//! per pair, so a large enough corpus will eventually produce one. At the earlier
//! 18-bit width a real pair did — `release/9999999999999999999999999176` and
//! `...234` in one repo — which is why the width is now 24. The property worth
//! relying on is the *independence*: truncation policy is a readability choice
//! with no effect on the collision rate.
//!
//! [`source_workspace_id`] covers git sources that name no ref (plain URL
//! specs), which cannot form a triple. Note that path specs (`dl ./some/dir`) do
//! not pass through this module at all — they reach devpod as a resolved
//! directory name — so an id handed to devpod is not necessarily one of these.
//!
//! See blooop/devlaunch#55 for the reasoning and #64 for the implementation
//! ticket.
//!
//! # Ported from `devlaunch/workspace_id.py`
//!
//! The derivation is reproduced byte for byte, pinned by golden vectors
//! generated by running the Python. Two of Python's regex behaviours are part of
//! that contract and are ported deliberately rather than tidied:
//!
//! - **`$` also matches before one trailing newline**, so `"x\n"` is a safe name
//!   while `"x\n\n"` and `"x\ny"` are not. The ref reaches the suffix hash
//!   verbatim, so tightening this would move ids Python already published.
//! - **`\w` under `re.UNICODE` is `str.isalnum()` plus `_`**, which is
//!   *category*-based (`L*`, `N*`). This port uses `char::is_alphanumeric()`,
//!   which is the `Alphabetic` property plus `N*` and therefore a strict
//!   superset: measured against Python 3.14 / UCD 16.0 it accepts 6167 more
//!   codepoints (4672 unassigned in the older UCD, 927 `Mn` and 438 `Mc`
//!   combining marks, 130 `So` enclosed letters). Every name Python accepts is
//!   accepted here and derives the same id, so no workspace on disk moves; the
//!   only difference is that a handful of names Python *refused* — an enclosed
//!   letter like `Ⓐ`, an Indic vowel sign like `ा`, a codepoint assigned after
//!   Python's UCD — are now accepted, and the slug rule erases all of them
//!   anyway. Plain combining accents (`U+0301` and friends) are *not* in that
//!   set: both runtimes refuse them, so an NFD ref is refused either way. Exact
//!   parity is not reachable without embedding a category table, and would not
//!   stay exact anyway — the `Cn` slice is Unicode version skew between the two
//!   runtimes, not a decision.
//!
//! `slug` needs no such caveat: it was checked against Python for all 1114112
//! codepoints and agrees on every one.

use std::fmt;

/// Total id budget. devpod's own ceiling is 48, but the setup pass's hostname
/// stage names the container after the workspace id, and downstream tooling
/// stacks prefixes and suffixes on it against a 64-byte limit
/// (kinisi-robotics/kinisi_ros#9766 already sat at 62/64). 48 is a ceiling
/// others eat into, not a budget to fill, so aim at 38.
pub(crate) const TARGET_LENGTH: usize = 38;

/// The repo slug is cut to this length when the id would otherwise overflow, and
/// is never cut below it. It carries no identity — only legibility — so trimming
/// it is safe, but trimming it to nothing would make `devpod list` unreadable.
pub(crate) const REPO_SLUG_LENGTH: usize = 20;

// 16 consonants x 4 vowels = 64 combinations = exactly 6 bits per syllable, so
// four syllables encode 24 bits of the digest in 8 pronounceable characters
// ("zovomobo", "hesirora", "lenevere") with no wordlist to keep in sync across
// languages.
//
// This was 3 syllables / 18 bits when the scheme was first decided. 18 bits put
// a birthday collision inside a single repo's plausible branch count — 500
// branches already produced one in test — so it was widened by one syllable. The
// extra two characters come out of the readable budget; the 38-char cap did not
// move.
const CONSONANTS: &[u8; 16] = b"bdfghjklmnprstvz";
const VOWELS: &[u8; 4] = b"aeio";
const SYLLABLES: usize = 4;

/// Bits of the digest the suffix encodes (6 per syllable).
///
/// Only this module's tests read it; the encoder walks the syllables instead.
#[cfg_attr(not(test), allow(dead_code))]
pub(crate) const SUFFIX_BITS: usize = SYLLABLES * 6;

/// Length of the identity-bearing suffix, in characters.
pub(crate) const SUFFIX_LENGTH: usize = SYLLABLES * 2;

/// Domain tag for ref-less sources, kept out of the triple's hash input so a URL
/// spec can never derive the same suffix as an `(owner, repo, ref)` workspace.
const SOURCE_KIND: &str = "source";

/// Which part of the triple was unsafe.
///
/// The part travels with the refusal because the caller renders it (Python's
/// `Invalid git {kind} name: ...`); core holds no user-facing English.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
// binary surface — not part of the frozen wf API (#251 §7)
pub enum NamePart {
    Owner,
    Repo,
    Ref,
}

/// A name that is not safe as a git ref or a path component.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
// binary surface — not part of the frozen wf API (#251 §7)
pub struct UnsafeName {
    pub part: NamePart,
    pub name: String,
}

/// Whether *name* is safe as a git ref and as a path component.
///
/// Starts with a word character (so it can never be read as a flag) and holds
/// only word characters, dots, slashes and dashes — Python's
/// `^[\w][\w./-]*$`, trailing-newline quirk included (see the module docs).
///
/// Bad input gets exactly one response in this codebase: it is rejected. The
/// previous split — one path raising while another coerced — meant the same bad
/// ref produced a hard error on one path and a silently different workspace on
/// another. Coercion is also what made the old derivation non-injective, since
/// five distinct refs coerced to one directory name. Rejecting is the honest
/// answer: a ref that is not a ref cannot be checked out later anyway, so the
/// only choice is where the user hears about it.
pub(crate) fn is_safe_name(name: &str) -> bool {
    let body = name.strip_suffix('\n').unwrap_or(name);
    let mut chars = body.chars();
    match chars.next() {
        Some(first) if is_word(first) => {}
        _ => return false,
    }
    chars.all(|c| is_word(c) || matches!(c, '.' | '/' | '-'))
}

fn is_word(c: char) -> bool {
    c == '_' || c.is_alphanumeric()
}

/// [`is_safe_name`] as a refusal that names the part it rejected.
pub(crate) fn validate_ref_name(name: &str, part: NamePart) -> Result<(), UnsafeName> {
    if is_safe_name(name) {
        Ok(())
    } else {
        Err(UnsafeName {
            part,
            name: name.to_string(),
        })
    }
}

/// Lowercase *text* and collapse every run of non-alphanumerics to one dash.
///
/// This is the only slug rule in devlaunch. It applies to the repo part and the
/// ref part alike, so `my_repo` becomes `my-repo` everywhere rather than
/// `my-repo` in one derivation and `myrepo` in another.
pub(crate) fn slug(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut in_run = false;
    for c in text.to_lowercase().chars() {
        if c.is_ascii_lowercase() || c.is_ascii_digit() {
            out.push(c);
            in_run = false;
        } else if !in_run {
            out.push('-');
            in_run = true;
        }
    }
    out.trim_matches('-').to_string()
}

/// Workspace id for a git source that names no ref, e.g. `github.com/owner/repo`.
///
/// A URL spec has no ref, so it cannot form an `(owner, repo, ref)` triple, but
/// it still reaches devpod as `--id`. It gets the same treatment as a triple:
/// slugged for legibility, suffixed for identity, capped at [`TARGET_LENGTH`]. A
/// bare slug would be both uncapped — a long URL reached 92 characters against
/// devpod's 48-char ceiling — and non-injective, since `my_repo`, `my-repo` and
/// `my.repo` all slug to the same string.
///
/// The hashed fields are the tag `"source"` and the lowercased *source*. The tag
/// keeps a ref-less source from ever sharing a suffix with a real workspace
/// triple. Lowercasing matches the triple's treatment of owner and repo: a host
/// is case-insensitive and so are GitHub owner and repo names, so two spellings
/// of one URL are one workspace.
pub(crate) fn source_workspace_id(source: &str) -> String {
    let suffix = syllable_suffix(&[SOURCE_KIND, &source.to_lowercase()]);
    let room = TARGET_LENGTH.saturating_sub(suffix.len() + 1);
    join(&[head(&slug(source), room).trim_matches('-'), &suffix])
}

/// A validated `(owner, repo, ref)` triple and the id derived from it.
///
/// Constructing this type is the parse boundary. It validates all three parts,
/// so holding a `WorkspaceId` is itself the evidence that the ref was checked —
/// no caller has to remember to validate, and no code path can skip it.
/// [`value`](Self::value) is the derived id, used verbatim as the devpod
/// workspace id and as the clone directory's leaf name.
///
/// The fields are private and there is no other constructor, which is what makes
/// an unvalidated triple unrepresentable rather than merely discouraged.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct WorkspaceId {
    owner: String,
    repo: String,
    git_ref: String,
}

impl WorkspaceId {
    /// Parse an unsanitized triple, or refuse it naming the part at fault.
    ///
    /// Parts are checked owner-first, because a caller that builds
    /// `repos_dir/<owner>/<repo>` needs the owner's verdict before it touches
    /// the filesystem.
    pub fn new(owner: &str, repo: &str, git_ref: &str) -> Result<Self, UnsafeName> {
        validate_ref_name(owner, NamePart::Owner)?;
        validate_ref_name(repo, NamePart::Repo)?;
        validate_ref_name(git_ref, NamePart::Ref)?;
        Ok(Self {
            owner: owner.to_string(),
            repo: repo.to_string(),
            git_ref: git_ref.to_string(),
        })
    }

    pub(crate) fn owner(&self) -> &str {
        &self.owner
    }

    pub(crate) fn repo(&self) -> &str {
        &self.repo
    }

    pub(crate) fn git_ref(&self) -> &str {
        &self.git_ref
    }

    /// The eight-character identity suffix. Never truncated.
    ///
    /// Owner and repo are lowercased before hashing because GitHub treats them
    /// case-insensitively: `NVIDIA/cuda-samples` and `nvidia/cuda-samples` are
    /// one repository, and giving each spelling its own id means one repo cloned
    /// twice into two containers. The ref is hashed verbatim — git refs really
    /// are case-sensitive, and `Main` and `main` can both exist in one repo.
    ///
    /// Lowercasing does not move ids for input that was already lowercase, which
    /// is every id this project has published.
    pub(crate) fn suffix(&self) -> String {
        syllable_suffix(&[
            &self.owner.to_lowercase(),
            &self.repo.to_lowercase(),
            &self.git_ref,
        ])
    }

    /// The derived id, at most [`TARGET_LENGTH`] characters.
    pub fn value(&self) -> String {
        let suffix = self.suffix();
        let mut repo_part = slug(&self.repo);
        // Cut the repo slug only when the id would otherwise overflow. Capping it
        // at REPO_SLUG_LENGTH leaves at least TARGET_LENGTH - 20 - 1 - 1 - 8 = 8
        // characters for the ref, so the ref budget can never go non-positive —
        // the hole that let a 47-char repo name skip truncation altogether.
        let untruncated = join(&[&repo_part, &fit_ref(&self.git_ref, TARGET_LENGTH), &suffix]);
        if untruncated.len() > TARGET_LENGTH {
            repo_part = head(&repo_part, REPO_SLUG_LENGTH)
                .trim_matches('-')
                .to_string();
        }
        let separators = if repo_part.is_empty() { 1 } else { 2 };
        let room = TARGET_LENGTH.saturating_sub(suffix.len() + repo_part.len() + separators);
        join(&[&repo_part, &fit_ref(&self.git_ref, room), &suffix])
    }
}

impl fmt::Display for WorkspaceId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.value())
    }
}

/// Eight characters of hashed identity for NUL-delimited *fields*.
///
/// The digest is taken over the fields joined by NUL, with no other
/// normalization applied here. The delimiter is what keeps field boundaries, so
/// `(a, bc)` stays distinct from `(ab, c)`; callers decide what to normalize
/// before calling.
///
/// This algorithm is frozen. Every workspace directory and devpod workspace on
/// disk is named by its output, so the tables, the syllable count, the digest,
/// the byte slice and the delimiter are all pinned by golden vectors taken from
/// the Python implementation.
fn syllable_suffix(fields: &[&str]) -> String {
    let digest = sha256(fields.join("\0").as_bytes());
    let mut head = [0u8; 8];
    head.copy_from_slice(&digest[..8]);
    let mut bits = u64::from_be_bytes(head);
    let mut out = String::with_capacity(SUFFIX_LENGTH);
    for _ in 0..SYLLABLES {
        out.push(CONSONANTS[((bits >> 2) & 15) as usize] as char);
        out.push(VOWELS[(bits & 3) as usize] as char);
        bits >>= 6;
    }
    out
}

/// Join non-empty *parts* with dashes, so an absent part leaves no stray dash.
fn join(parts: &[&str]) -> String {
    let mut out = String::new();
    for part in parts.iter().filter(|part| !part.is_empty()) {
        if !out.is_empty() {
            out.push('-');
        }
        out.push_str(part);
    }
    out
}

/// The first *n* characters of *s*, like Python's `s[:n]`.
fn head(s: &str, n: usize) -> &str {
    match s.char_indices().nth(n) {
        Some((end, _)) => &s[..end],
        None => s,
    }
}

/// Slug *git_ref* down to *room* characters, dropping whole segments first.
///
/// Refs are path-shaped, and their middle segments are usually taxonomy while
/// the ends carry the meaning. Truncating characters first turns
/// `dependabot/github_actions/codecov/codecov-action-6` into
/// `dependabot-github-actions-`, which says nothing about *which* action.
/// Dropping middle segments instead keeps `dependabot-codecov-action-6`.
fn fit_ref(git_ref: &str, room: usize) -> String {
    let mut segments: Vec<String> = git_ref
        .split('/')
        .map(slug)
        .filter(|segment| !segment.is_empty())
        .collect();
    while segments.len() > 2 && segments.join("-").len() > room {
        segments.remove(1);
    }
    head(&segments.join("-"), room)
        .trim_matches('-')
        .to_string()
}

/// SHA-256 (FIPS 180-4), because the frozen suffix is defined by this digest.
/// The `sha2` crate rather than a hand-rolled compression function: the golden
/// ids pin the output either way, and crypto primitives are the one place
/// "no dependency" costs more review than it saves.
fn sha256(message: &[u8]) -> [u8; 32] {
    use sha2::Digest;
    sha2::Sha256::digest(message).into()
}

