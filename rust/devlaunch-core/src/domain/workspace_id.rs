    #[test]
    fn truncation_contributes_no_collisions() {
        // 500 refs whose readable part truncates to one byte-identical string: the
        // number of distinct ids must equal the number of distinct suffixes, so
        // truncation adds nothing on top of the suffix's own birthday rate.
        let parsed: Vec<WorkspaceId> = (0..500)
            .map(|i| {
                id(
                    "blooop",
                    "a-repo-name-that-is-long",
                    &format!("feature/shared-prefix-{i}"),
                )
            })
            .collect();
        let readable: HashSet<String> = parsed
            .iter()
            .map(|w| drop_last_segment(&w.value()))
            .collect();
        assert_eq!(
            readable.len(),
            1,
            "the corpus must collide before truncation"
        );
        let values: HashSet<String> = parsed.iter().map(|w| w.value()).collect();
        let suffixes: HashSet<String> = parsed.iter().map(|w| w.suffix()).collect();
        assert_eq!(values.len(), suffixes.len());
    }

    fn drop_last_segment(value: &str) -> String {
        match value.rsplit_once('-') {
            Some((head, _)) => head.to_string(),
            None => value.to_string(),
        }
    }

